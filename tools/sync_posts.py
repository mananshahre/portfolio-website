#!/usr/bin/env python3
"""Sync published posts from Firestore to static pages.

Uses an authenticated build identity and reads only documents with status == 'published' (the build identity must have published-only read access). Renders each into post-<slug>.html from
post-template.html and rebuilds the listing inside blog.html's
POSTS:BEGIN/END markers. Runs in GitHub Actions; also runnable locally.

Markdown subset (must stay in sync with write.html's renderer):
paragraphs split on blank lines, '## ' heading, '> ' quote,
**bold**, *italic*, [text](https://url). HTML is escaped first.
"""
import json
import os
import re
import sys
import urllib.request
from datetime import datetime
from zoneinfo import ZoneInfo
from html import escape

PROJECT = os.environ.get("FIREBASE_PROJECT", "becoming-manan-blog")
def build_token():
    token = os.environ.get("FIREBASE_ID_TOKEN")
    if token:
        return token
    password = os.environ.get("FIREBASE_BUILD_PASSWORD")
    key = os.environ.get("FIREBASE_API_KEY")
    if not password or not key:
        raise SystemExit("Build identity not configured; nothing changed")
    payload = {"email": "blog-sync@becoming-manan-blog.invalid",
               "password": password, "returnSecureToken": True}
    request = urllib.request.Request(
        "https://identitytoolkit.googleapis.com/v1/accounts:signInWithPassword?key=" + key,
        data=json.dumps(payload).encode(), headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            result = json.load(response)
    except Exception:
        raise SystemExit("Build sign-in failed; nothing changed") from None
    if result.get("localId") != "KYqMLKtEsSZ79NTrvfYPRU13p9Q2":
        raise SystemExit("Unexpected build identity; nothing changed")
    return result["idToken"]


ACCESS_TOKEN = build_token()
SITE_DIR = sys.argv[1] if len(sys.argv) > 1 else "mananshahre-portfolio"

URL = f"https://firestore.googleapis.com/v1/projects/{PROJECT}/databases/(default)/documents:runQuery"


def fetch_posts():
    payload = {"structuredQuery": {"from": [{"collectionId": "posts"}],
        "where": {"fieldFilter": {"field": {"fieldPath": "status"},
        "op": "EQUAL", "value": {"stringValue": "published"}}}}}
    req = urllib.request.Request(URL, data=json.dumps(payload).encode(),
        headers={"Accept": "application/json", "Content-Type": "application/json", "Authorization": "Bearer " + ACCESS_TOKEN})
    with urllib.request.urlopen(req, timeout=30) as r:
        data = json.load(r)
    posts = []
    for item in data:
        document = item.get("document")
        if not document:
            continue
        f = document.get("fields", {})
        if f.get("status", {}).get("stringValue") != "published":
            raise ValueError("Unexpected non-public document in query")
        posts.append({
            "id": document["name"].rsplit("/", 1)[-1],
            "title": f.get("title", {}).get("stringValue", "(untitled)"),
            "body": f.get("body", {}).get("stringValue", ""),
            "publishedAt": f.get("publishedAt", {}).get("timestampValue", ""),
        })
    posts.sort(key=lambda p: p["publishedAt"], reverse=True)
    return posts


def inline(text):
    s = escape(text, quote=True)
    s = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"\*([^*]+)\*", r"<em>\1</em>", s)
    s = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)", r'<a href="\2">\1</a>', s)
    return s


def render(src):
    out = []
    for block in re.split(r"\n\s*\n", src):
        b = block.strip()
        if not b:
            continue
        if b.startswith("## "):
            out.append("  <h3>" + inline(b[3:]) + "</h3>")
        elif b.startswith("> "):
            out.append('  <blockquote class="article-quote">\n    <p>' + inline(b[2:]) + "</p>\n  </blockquote>")
        else:
            out.append("  <p>" + inline(b).replace("\n", "<br>") + "</p>")
    return "\n".join(out)


def slugify(title, doc_id):
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:60] or "post"
    return f"{slug}-{doc_id}"


def fmt_date(ts):
    if not ts:
        return ""
    dt = datetime.fromisoformat(ts.replace("Z", "+00:00")).astimezone(ZoneInfo("Asia/Kolkata"))
    # Dates follow the author's India timezone.
    return dt.strftime("%-d %B %Y")


def main():
    try:
        posts = fetch_posts()
    except Exception:
        raise SystemExit('Published-post read failed; nothing changed') from None
    template = open(os.path.join(SITE_DIR, "post-template.html"), encoding="utf-8").read()

    # Delete only files generated by a previous successful sync, never hand-written posts.
    manifest_path = os.path.join(SITE_DIR, '.generated-posts.json')
    try:
        previous = set(json.load(open(manifest_path, encoding='utf-8')))
    except FileNotFoundError:
        previous = set()
    if any(not re.fullmatch(r'post-[a-z0-9-]+-[A-Za-z0-9_-]+\.html', f) for f in previous):
        raise SystemExit('Invalid generated-post manifest; nothing changed')
    keep_pages = set()
    pending_pages = {}
    cards = []
    for p in posts:
        slug = slugify(p["title"], p["id"])
        fname = f"post-{slug}.html"
        keep_pages.add(fname)
        date = fmt_date(p["publishedAt"])
        values = {"TITLE": escape(p["title"]), "DATE": date, "BODY": render(p["body"])}
        page = re.sub(r"\{\{(TITLE|DATE|BODY)\}\}", lambda m: values[m[1]], template)
        pending_pages[fname] = page
        excerpt = escape(re.sub(r"\s+", " ", re.sub(r"[*#>\[\]]", "", p["body"]))[:180].strip())
        cards.append(
            '    <article class="post-card">\n'
            f'      <p class="post-meta">{date}</p>\n'
            f'      <h3><a href="{fname}">{escape(p["title"])}</a></h3>\n'
            f'      <p>{excerpt}&hellip;</p>\n'
            f'      <p class="post-more"><a href="{fname}">Read the post &#8594;</a></p>\n'
            "    </article>"
        )

    listing = "\n".join(cards) if cards else '    <p style="color:var(--dim)">First post is on its way.</p>'

    blog_path = os.path.join(SITE_DIR, "blog.html")
    blog = open(blog_path, encoding="utf-8").read()
    new_blog, n = re.subn(
        r"<!-- POSTS:BEGIN -->.*?<!-- POSTS:END -->",
        lambda _: "<!-- POSTS:BEGIN -->\n" + listing + "\n    <!-- POSTS:END -->",
        blog, flags=re.S)
    if n != 1:
        raise SystemExit("POSTS markers not found exactly once in blog.html")
    def replace_text(path, text):
        temp = path + '.tmp'
        with open(temp, 'w', encoding='utf-8') as fh:
            fh.write(text)
        os.replace(temp, path)

    for fname, page in pending_pages.items():
        replace_text(os.path.join(SITE_DIR, fname), page)
    if new_blog != blog:
        replace_text(blog_path, new_blog)
    for fname in previous - keep_pages:
        path = os.path.join(SITE_DIR, fname)
        if os.path.exists(path):
            os.remove(path)
    replace_text(manifest_path, json.dumps(sorted(keep_pages), indent=2) + '\n')

    print(f"synced {len(posts)} published post(s)")


if __name__ == "__main__":
    main()
